def читать_доступ():
    env = {}
    for строка in ФАЙЛ_ДОСТУПА.read_text(encoding="utf-8").splitlines():
        строка = строка.strip()
        if строка and not строка.startswith("#") and "=" in строка:
            k, v = строка.split("=", 1)
            env[k.strip()] = v.strip()
    for k in ("AMO_SUBDOMAIN", "AMO_PIPELINE_ID", "AMO_TOKEN"):
        if k not in env:
            raise SystemExit(f"в {ФАЙЛ_ДОСТУПА.name} нет {k}")
    return env["AMO_SUBDOMAIN"], int(env["AMO_PIPELINE_ID"]), env["AMO_TOKEN"]


class Amo:
    def __init__(self):
        self.sub, self.pipeline_id, self._token = читать_доступ()
        self.base = f"https://{self.sub}.amocrm.ru/api/v4"
        self._lock = threading.Lock()
        self._last = 0.0

    def _call(self, method, path, body=None):
        # amoCRM: не чаще ~7 запросов/с
        with self._lock:
            пауза = 0.2 - (time.time() - self._last)
            if пауза > 0:
                time.sleep(пауза)
            self._last = time.time()
        данные = json.dumps(body, ensure_ascii=False).encode("utf-8") if body is not None else None
        req = request.Request(self.base + path, data=данные, method=method,
                              headers={"Authorization": "Bearer " + self._token,
                                       "Content-Type": "application/json"})
        for попытка in range(5):
            try:
                with request.urlopen(req, timeout=60) as f:
                    сырое = f.read()
                    return json.loads(сырое) if сырое else None
            except error.HTTPError as e:
                if e.code in (429, 500, 502, 503, 504) and попытка < 4:
                    time.sleep(1.5 * (попытка + 1))
                    continue
                тело = e.read().decode("utf-8", "replace")[:500]
                raise RuntimeError(f"amoCRM {method} {path}: HTTP {e.code} {тело}")
            except (error.URLError, TimeoutError) as e:
                if попытка < 4:
                    time.sleep(1.5 * (попытка + 1))
                    continue
                raise

    def get(self, path):
        return self._call("GET", path)

    def все_страницы(self, path, ключ):
        итог, page = [], 1
        while True:
            разделитель = "&" if "?" in path else "?"
            d = self.get(f"{path}{разделитель}limit=250&page={page}")
            if not d or "_embedded" not in d:
                break
            часть = d["_embedded"].get(ключ, [])
            итог.extend(часть)
            if len(часть) < 250:
                break
            page += 1
        return итог

    # --- чтение -----------------------------------------------------------
    def воронка(self):
        return self.get(f"/leads/pipelines/{self.pipeline_id}")

    def сделки(self):
        return self.все_страницы(f"/leads?filter[pipeline_id]={self.pipeline_id}&with=contacts,loss_reason", "leads")

    def контакт(self, cid):
        return self.get(f"/contacts/{cid}")

    def примечания(self, lead_id):
        return self.все_страницы(f"/leads/{lead_id}/notes", "notes")

    def задачи(self, lead_id):
        return self.все_страницы(f"/tasks?filter[entity_type]=leads&filter[entity_id]={lead_id}", "tasks")

    def причины_проигрыша(self):
        try:
            return {x["id"]: x["name"] for x in self.все_страницы("/leads/loss_reasons", "loss_reasons")}
        except Exception:
            return {}

    # --- запись: ТОЛЬКО своё примечание -------------------------------------
    def записать_аудит(self, lead_id, текст):
        """Найти своё примечание (первая строка ИМЯ_АУДИТА) и переписать; нет — добавить одно."""
        своё = None
        for n in self.примечания(lead_id):
            t = (n.get("params") or {}).get("text") or ""
            if n.get("note_type") == "common" and t.strip().split("\n", 1)[0].strip() == ИМЯ_АУДИТА:
                своё = n
                break
        if своё:
            try:
                self._call("PATCH", f"/leads/{lead_id}/notes",
                           [{"id": своё["id"], "note_type": "common", "params": {"text": текст}}])
            except RuntimeError:
                self._call("PATCH", f"/leads/{lead_id}/notes/{своё['id']}",
                           {"note_type": "common", "params": {"text": текст}})
            return "обновлено", своё["id"]
        r = self._call("POST", f"/leads/{lead_id}/notes",
                       [{"note_type": "common", "params": {"text": текст}}])
        nid = None
        try:
            nid = r["_embedded"]["notes"][0]["id"]
        except Exception:
            pass
        return "добавлено", nid


