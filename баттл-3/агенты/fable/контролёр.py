def норм(s):
    s = unicodedata.normalize("NFKC", s or "").lower()
    s = s.replace("ё", "е").replace("«", '"').replace("»", '"').replace("“", '"').replace("”", '"')
    s = re.sub(r"[^\w\s]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def найти_цитату(цитата, обезличенный_текст):
    if not цитата:
        return False
    if цитата in обезличенный_текст:
        return True
    return норм(цитата) in норм(обезличенный_текст)


def проверить_вердикт(вердикт, номера, обезличенный_текст):
    чистые, отброшено = [], []
    видели = set()
    for н in вердикт.get("нарушения") or []:
        пункт = str(н.get("пункт", "")).strip()
        if пункт not in номера:
            отброшено.append((н, "нет такого пункта в стандарте"))
            continue
        if пункт in видели:
            отброшено.append((н, "повтор пункта"))
            continue
        цитата = str(н.get("цитата") or "").strip().strip("«»\"")
        if not найти_цитату(цитата, обезличенный_текст):
            отброшено.append((н, "цитата не найдена в тексте сделки"))
            continue
        видели.add(пункт)
        чистые.append({"пункт": пункт, "суть": str(н.get("суть") or "").strip().rstrip("."),
                       "цитата": цитата, "источник": ("звонок" if "звон" in str(н.get("источник", "")).lower()
                                                     else "карточка" if "карт" in str(н.get("источник", "")).lower() else "чат"),
                       "время": str(н.get("время") or "").strip()})
    чистые.sort(key=lambda x: [int(p) for p in x["пункт"].split(".")])
    return чистые, отброшено


