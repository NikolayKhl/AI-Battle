class Расход:
    def __init__(self):
        self.lock = threading.Lock()
        self.вызовов = 0
        self.вход = 0
        self.выход = 0
        self.модели = {}
        self.начало = time.time()

    def учесть(self, ответ_cli, код):
        u = ответ_cli.get("usage") or {}
        вход = int(u.get("input_tokens", 0)) + int(u.get("cache_creation_input_tokens", 0)) + int(u.get("cache_read_input_tokens", 0))
        выход = int(u.get("output_tokens", 0))
        with self.lock:
            self.вызовов += 1
            self.вход += вход
            self.выход += выход
            for имя, mu in (ответ_cli.get("modelUsage") or {}).items():
                m = self.модели.setdefault(имя, {"вход": 0, "выход": 0})
                m["вход"] += int(mu.get("inputTokens", 0)) + int(mu.get("cacheReadInputTokens", 0)) + int(mu.get("cacheCreationInputTokens", 0))
                m["выход"] += int(mu.get("outputTokens", 0))
            ПАПКА_ДАННЫХ.mkdir(exist_ok=True)
            with open(ФАЙЛ_РАСХОДА_ПОДРОБНО, "a", encoding="utf-8") as f:
                f.write(json.dumps({"когда": datetime.now(МСК).isoformat(timespec="seconds"), "сделка": код,
                                    "вход": вход, "выход": выход, "секунд": round(ответ_cli.get("duration_ms", 0) / 1000, 1),
                                    "modelUsage": ответ_cli.get("modelUsage")}, ensure_ascii=False) + "\n")

    def модель(self):
        # основная модель — та, что съела больше всего токенов
        if not self.модели:
            return МОДЕЛЬ
        return max(self.модели.items(), key=lambda kv: kv[1]["вход"] + kv[1]["выход"])[0]


def вызвать_модель(системный, пользовательский):
    cmd = ["claude", "-p", "--tools", "", "--model", МОДЕЛЬ, "--output-format", "json",
           "--no-session-persistence", "--effort", os.environ.get("FABLE_EFFORT", "high"),
           "--system-prompt", системный]
    окружение = {k: v for k, v in os.environ.items() if not k.startswith("CLAUDE")}
    p = subprocess.run(cmd, input=пользовательский, capture_output=True, text=True, timeout=900, env=окружение,
                       cwd=str(ПАПКА_ДАННЫХ))
    if p.returncode != 0:
        raise RuntimeError(f"claude CLI завершился с кодом {p.returncode}: {p.stderr[-800:]}")
    ответ = json.loads(p.stdout)
    if ответ.get("is_error"):
        raise RuntimeError(f"claude CLI: ошибка: {str(ответ.get('result'))[:800]}")
    return ответ


def вытащить_json(текст):
    текст = текст.strip()
    m = re.search(r"\{.*\}", текст, re.S)
    if not m:
        raise ValueError("в ответе модели нет JSON")
    return json.loads(m.group(0))


