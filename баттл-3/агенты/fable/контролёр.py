    ответ2 = вызвать_модель(ПРОМПТ_ОТВЕТОВ, данные)
    расход.учесть(ответ2, "ответы")
    ФАЙЛ_ОТВЕТОВ.write_text(подставить_имена((ответ2.get("result") or "").strip()) + "\n", encoding="utf-8")
    print(f"письмо: {ФАЙЛ_ПИСЬМА.name}, ответы: {ФАЙЛ_ОТВЕТОВ.name}")


