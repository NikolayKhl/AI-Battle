def мск(ts):
    return datetime.fromtimestamp(int(ts), tz=МСК)


def метка(dt):
    return f"{dt:%d.%m %H:%M}"


def рабочее(dt):
    return dt.weekday() < 5 and РАБ_НАЧАЛО <= dt.hour < РАБ_КОНЕЦ


def рабочих_минут(a, b):
    """Сколько минут рабочего времени (09–19 будни) между a и b."""
    if b <= a:
        return 0
    минут, t = 0, a.replace(second=0, microsecond=0)
    # шаг по часу — точность достаточная для суждения о «30 минутах» и «рабочем дне»
    while t < b:
        след = min(b, (t + timedelta(hours=1)).replace(minute=0, second=0, microsecond=0))
        if след <= t:
            след = b
        if рабочее(t):
            минут += (след - t).total_seconds() / 60
        t = след
    return int(round(минут))


def человекочасы(мин):
    if мин < 60:
        return f"{мин} мин"
    ч = мин / 60
    return f"{ч:.1f} ч" if ч < 10 else f"{ч:.0f} ч (≈{ч/10:.1f} раб. дня)"


РОЛИ = (("Клиент:", "клиент"), ("Менеджер:", "менеджер"))


def разобрать_текст_примечания(text):
    """Возвращает (тип, роль, тело): чат клиента/менеджера, расшифровка, служебное."""
    t = text.strip()
    if t.startswith("Расшифровка звонка"):
        return "расшифровка", None, t
    for префикс, роль in РОЛИ:
        if t.startswith(префикс):
            return "чат", роль, t[len(префикс):].strip()
    return "прочее", None, t


def собрать_сделку(amo, lead, справочники):
    """Читает всё по сделке и строит хронологию (список событий)."""
    статусы, причины = справочники["статусы"], справочники["причины"]
    lid = lead["id"]
    m = re.search(r"\b(D-\d{2})\b", lead["name"])
    код = m.group(1) if m else str(lid)
    поля = {c["field_name"]: (c["values"][0]["value"] if c.get("values") else None)
            for c in (lead.get("custom_fields_values") or [])}
    менеджер = поля.get("Менеджер") or "?"
    контакты = []
    for c in (lead.get("_embedded", {}).get("contacts") or []):
        try:
            контакты.append(amo.контакт(c["id"]))
        except Exception:
            pass
    клиент = контакты[0]["name"] if контакты else lead["name"].split("—")[0].strip()
    телефоны, почты = [], []
    for c in контакты:
        for f in (c.get("custom_fields_values") or []):
            for v in (f.get("values") or []):
                if f.get("field_code") == "PHONE":
                    телефоны.append(str(v["value"]))
                elif f.get("field_code") == "EMAIL":
                    почты.append(str(v["value"]))

    статус_id = lead["status_id"]
    статус = статусы.get(статус_id, str(статус_id))
    закрыта = статус_id in (142, 143)
    исход = {142: "выиграна", 143: "проиграна"}.get(статус_id, "открыта")
    причина = причины.get(lead.get("loss_reason_id")) if lead.get("loss_reason_id") else None

    события = []
    for n in amo.примечания(lid):
        p = n.get("params") or {}
        тип = n.get("note_type")
        ts = n["created_at"]
        if тип == "common":
            текст = p.get("text") or ""
            if текст.strip().startswith("АУДИТ "):
                continue  # свои и чужие вердикты — не материал
            вид, роль, тело = разобрать_текст_примечания(текст)
            события.append({"ts": ts, "вид": вид, "роль": роль, "текст": тело})
        elif тип in ("call_in", "call_out"):
            события.append({"ts": ts, "вид": "звонок", "роль": "менеджер" if тип == "call_out" else "клиент",
                            "текст": "", "направление": "исходящий" if тип == "call_out" else "входящий",
                            "длит": p.get("duration"), "результат": p.get("call_result"), "телефон": p.get("phone")})
        else:
            текст = json.dumps(p, ensure_ascii=False) if p else ""
            события.append({"ts": ts, "вид": "прочее", "роль": None, "текст": f"[{тип}] {текст}"})
    события.sort(key=lambda e: e["ts"])

    задачи = []
    for t in amo.задачи(lid):
        задачи.append({"текст": t.get("text") or "", "создана": t["created_at"],
                       "дедлайн": t.get("complete_till"), "выполнена": bool(t.get("is_completed")),
                       "итог": ((t.get("result") or {}).get("text") or "")})

    return {
        "код": код, "id": lid, "название": lead["name"], "менеджер": менеджер,
        "клиент": клиент, "телефоны": телефоны, "почты": почты, "сумма": lead.get("price") or 0,
        "источник": поля.get("Источник заявки"), "статус": статус, "исход": исход, "причина_проигрыша": причина,
        "создана": lead["created_at"], "закрыта": lead.get("closed_at") if закрыта else None,
        "обновлена": lead.get("updated_at"), "события": события, "задачи": задачи,
        "контактные_имена": [c.get("name") or "" for c in контакты] +
                            [c.get("first_name") or "" for c in контакты] +
                            [c.get("last_name") or "" for c in контакты],
    }


