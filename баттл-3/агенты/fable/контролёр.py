def main(argv):
    if not argv or argv in (["-h"], ["--help"]):
        print(__doc__)
        return 0
    global СУХО
    СУХО = "--сухо" in argv
    все = "--все" in argv
    только_письмо = "--письмо" in argv and not все
    коды = {a.upper() for a in argv if re.fullmatch(r"[dD]-\d{2}", a)}
    if только_письмо:
        расход = Расход()
        написать_письмо(расход)
        строка = {"прогон": "письмо", "модель": расход.модель(), "как": "подписка",
                  "вызовов": расход.вызовов, "вход_токенов": расход.вход, "выход_токенов": расход.выход,
                  "секунд": int(round(time.time() - расход.начало))}
        ФАЙЛ_РАСХОДА.write_text(json.dumps(строка, ensure_ascii=False) + "\n", encoding="utf-8")
        print(json.dumps(строка, ensure_ascii=False))
        return 0
    if not все and not коды:
        print("укажи коды сделок (D-09) или --все")
        return 2

    стандарт = ФАЙЛ_СТАНДАРТА.read_text(encoding="utf-8")
    номера = номера_стандарта(стандарт)
    amo = Amo()
    воронка = amo.воронка()
    справочники = {"статусы": {s["id"]: s["name"] for s in воронка["_embedded"]["statuses"]},
                   "причины": amo.причины_проигрыша()}
    сделки = amo.сделки()
    if not все:
        сделки = [l for l in сделки if any(re.search(rf"\b{k}\b", l["name"]) for k in коды)]
        найдено = {re.search(r"\b(D-\d{2})\b", l["name"]).group(1) for l in сделки if re.search(r"\b(D-\d{2})\b", l["name"])}
        for k in sorted(коды - найдено):
            print(f"ОШИБКА: сделка {k} в воронке не найдена", file=sys.stderr)
    сделки.sort(key=lambda l: l["name"])
    if not сделки:
        print("нечего проверять")
        return 1

    название_прогона = "все сорок" if все else ", ".join(sorted(коды))
    дата_проверки = datetime.now(МСК)
    расход = Расход()
    lock = threading.Lock()

    def лог(msg):
        with lock:
            print(msg, flush=True)

    ошибки = []

    def работа(lead):
        try:
            return проверить_сделку(amo, lead, справочники, стандарт, номера, расход, дата_проверки, лог)
        except Exception as e:
            имя = lead.get("name", "?")
            лог(f"ОШИБКА {имя}: {e}")
            ошибки.append((имя, str(e)))
            return None

    with ThreadPoolExecutor(max_workers=max(1, ПАРАЛЛЕЛЬНО)) as pool:
        итоги = [x for x in pool.map(работа, сделки) if x]

    if СУХО:
        return 0
