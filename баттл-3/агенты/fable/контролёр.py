def написать_письмо(расход):
    итоги, данные = данные_для_письма()
    if not итоги:
        print("письмо: нет вердиктов")
        return
    имена = {и["код"]: и["клиент"] for и in итоги}

    def подставить_имена(текст):
        # «D-17» → «D-17 (Светлана Дорохова)» — первое упоминание в каждом абзаце
        def repl(m):
            return f"{m.group(0)} ({имена[m.group(0)]})" if m.group(0) in имена else m.group(0)
        абзацы = []
        for абзац in текст.split("\n"):
            видели = set()
            def r2(m):
                k = m.group(0)
                if k in имена and k not in видели:
                    видели.add(k)
                    return f"{k} ({имена[k]})"
                return k
            абзацы.append(re.sub(r"\bD-\d{2}\b", r2, абзац))
        return "\n".join(абзацы)

    ответ = вызвать_модель(ПРОМПТ_ПИСЬМА, данные)
    расход.учесть(ответ, "письмо")
    письмо = подставить_имена((ответ.get("result") or "").strip())
    письмо += "\n\n---\n_Письмо собрано контролёром FABLE автоматически из `нарушения.csv` и `сводка.md`; " \
              f"проверено сделок: {len(итоги)}, нарушений: {sum(len(и['нарушения']) for и in итоги)}._\n"
