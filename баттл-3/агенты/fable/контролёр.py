ТЕЛЕФОН = re.compile(r"(?<!\d)(?:\+7|8|7)[\s\-(]*\d{3}[\s\-)]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}(?!\d)")
ПОЧТА = re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")


class Маска:
    """Заменяет ПД клиента на метки. Хранит формы, чтобы потом вернуть цитату как есть."""

    def __init__(self, сделка):
        self.формы = {}          # метка -> set(исходных форм)
        self.правила = []        # (regex, метка)
        имена = set()
        for имя in [сделка["клиент"]] + сделка["контактные_имена"]:
            for часть in re.split(r"[\s\-]+", имя or ""):
                if len(часть) >= 3:
                    имена.add(часть)
        менеджер_части = {ч.lower() for ч in re.split(r"[\s\-]+", сделка.get("менеджер") or "") if ч}
        # имя клиента с падежными окончаниями: Сергей → Сергея/Сергею, Панов → Панова/Панову
        for имя in sorted(имена, key=len, reverse=True):
            основа = имя[:-1] if len(имя) > 4 else имя
            # имя совпадает с именем менеджера («Ольга» и там и там) — нейтральная метка, чтобы не путать роли
            метка_имени = "Имя" if имя.lower() in менеджер_части else "Клиент"
            self.правила.append((re.compile(rf"(?<!\w){re.escape(основа)}\w{{0,3}}(?!\w)", re.IGNORECASE), метка_имени))
        for i, тел in enumerate(сделка["телефоны"], 1):
            цифры = re.sub(r"\D", "", тел)[-10:]
            self.правила.append((re.compile(r"(?<!\d)(?:\+7|8|7)?[\s\-(]*" + r"[\s\-)]*".join(цифры[:3]) + r"[\s\-)]*" +
                                            r"[\s\-]*".join(цифры[3:]) + r"(?!\d)"), f"<тел-{i}>"))
        for i, п in enumerate(сделка["почты"], 1):
            self.правила.append((re.compile(re.escape(п), re.IGNORECASE), f"<почта-{i}>"))
        # отчество после имени клиента: «Клиент Викторовна» → «Клиент Отчество»
        self.правила.append((re.compile(r"(?<=(?<!\w)Клиент )[А-ЯЁ][а-яё]+(?:овна|евна|ична|инична|ович|евич|ич)(?!\w)"), "Отчество"))
        self.правила.append((re.compile(r"(?<=(?<!\w)Имя )[А-ЯЁ][а-яё]+(?:овна|евна|ична|инична|ович|евич|ич)(?!\w)"), "Отчество"))
        # любые другие телефоны/почты в тексте
        self.правила.append((ТЕЛЕФОН, "<тел>"))
        self.правила.append((ПОЧТА, "<почта>"))

    def скрыть(self, текст):
        if not текст:
            return текст
        for rx, метка in self.правила:
            def подмена(m, метка=метка):
                self.формы.setdefault(метка, set()).add(m.group(0))
                return метка
            текст = rx.sub(подмена, текст)
        return текст

    def раскрыть(self, цитата, исходники):
        """Найти в исходных (необезличенных) текстах фрагмент, соответствующий обезличенной цитате."""
        части = re.split(r"(Клиент|Имя|Отчество|<тел-\d+>|<почта-\d+>|<тел>|<почта>)", цитата)
        if len(части) == 1:
            return цитата
        шаблон = ""
        for ч in части:
            if ч in self.формы and self.формы[ч]:
                шаблон += "(?:" + "|".join(re.escape(f) for f in sorted(self.формы[ч], key=len, reverse=True)) + ")"
            elif ч in ("Клиент", "Имя", "Отчество", "<тел>", "<почта>") or re.fullmatch(r"<(тел|почта)-\d+>", ч):
                шаблон += r"\S+"
            else:
                шаблон += re.escape(ч)
        rx = re.compile(шаблон.replace(r"\ ", r"\s+"), re.IGNORECASE)
        for текст in исходники:
            m = rx.search(текст)
            if m:
                return m.group(0)
        return цитата

    def таблица(self):
        return {метка: sorted(формы) for метка, формы in self.формы.items()}


