def записать_csv_и_сводку(стандарт):
    итоги = []
    for f in sorted(ПАПКА_ВЕРДИКТОВ.glob("D-*.json")):
        итоги.append(json.loads(f.read_text(encoding="utf-8")))
    with open(ФАЙЛ_НАРУШЕНИЙ, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(["сделка", "менеджер", "клиент", "сумма", "исход", "стадия", "пункт", "суть", "цитата", "источник", "время"])
        for и in итоги:
            for н in и["нарушения"]:
                w.writerow([и["код"], и["менеджер"], и["клиент"], и["сумма"], и["исход"], и["статус"],
                            н["пункт"], н["суть"], н["цитата_исх"], н["источник"], н["время"]])
    # сводка — только арифметика из тех же данных
    from collections import Counter, defaultdict
    всего = sum(len(и["нарушения"]) for и in итоги)
    по_менеджеру = defaultdict(lambda: {"сделок": 0, "чистых": 0, "нарушений": 0, "пункты": Counter(),
                                        "выиграно": 0, "проиграно": 0, "сумма_проиграно_с_наруш": 0})
    по_исходу = defaultdict(lambda: {"сделок": 0, "с_нарушениями": 0, "нарушений": 0, "пункты": Counter()})
    по_пункту = Counter()
    for и in итоги:
        m = по_менеджеру[и["менеджер"]]
        m["сделок"] += 1
        m["нарушений"] += len(и["нарушения"])
        m["чистых"] += 0 if и["нарушения"] else 1
        if и["исход"] == "выиграна":
            m["выиграно"] += 1
        if и["исход"] == "проиграна":
            m["проиграно"] += 1
            if и["нарушения"]:
                m["сумма_проиграно_с_наруш"] += и["сумма"] or 0
        for н in и["нарушения"]:
            m["пункты"][н["пункт"]] += 1
            по_пункту[н["пункт"]] += 1
        o = по_исходу[и["исход"]]
        o["сделок"] += 1
        o["с_нарушениями"] += 1 if и["нарушения"] else 0
        o["нарушений"] += len(и["нарушения"])
        for н in и["нарушения"]:
            o["пункты"][н["пункт"]] += 1
    s = [f"# Сводка FABLE — {len(итоги)} сделок, {всего} нарушений", ""]
    s.append("## По сделкам")
    s.append("| сделка | менеджер | исход | сумма | нарушений | пункты |")
    s.append("|---|---|---|---:|---:|---|")
    for и in итоги:
        s.append(f"| {и['код']} | {и['менеджер']} | {и['исход']} | {и['сумма']} | {len(и['нарушения'])} | "
                 f"{', '.join(н['пункт'] for н in и['нарушения']) or '—'} |")
    s.append("")
    s.append("## По менеджерам")
    s.append("| менеджер | сделок | выиграно | проиграно | чистых сделок | нарушений | нарушений/сделку | что чаще всего |")
    s.append("|---|---:|---:|---:|---:|---:|---:|---|")
    for имя, m in sorted(по_менеджеру.items(), key=lambda kv: kv[1]["нарушений"] / max(kv[1]["сделок"], 1)):
        s.append(f"| {имя} | {m['сделок']} | {m['выиграно']} | {m['проиграно']} | {m['чистых']} | {m['нарушений']} | "
                 f"{m['нарушений']/max(m['сделок'],1):.2f} | {', '.join(f'{п}×{n}' for п, n in m['пункты'].most_common(4)) or '—'} |")
    s.append("")
    s.append("## Выигранные против проигранных")
    s.append("| исход | сделок | с нарушениями | нарушений | нарушений/сделку | пункты |")
    s.append("|---|---:|---:|---:|---:|---|")
    for исход in ("выиграна", "проиграна", "открыта"):
        if исход in по_исходу:
            o = по_исходу[исход]
            s.append(f"| {исход} | {o['сделок']} | {o['с_нарушениями']} | {o['нарушений']} | {o['нарушений']/max(o['сделок'],1):.2f} | "
                     f"{', '.join(f'{п}×{n}' for п, n in o['пункты'].most_common(8)) or '—'} |")
    s.append("")
    s.append("## По пунктам стандарта")
    for п, n in sorted(по_пункту.items(), key=lambda kv: (-kv[1], kv[0])):
        s.append(f"- {п}: {n}")
    ФАЙЛ_СВОДКИ.write_text("\n".join(s) + "\n", encoding="utf-8")
    return итоги


