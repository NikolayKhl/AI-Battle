def build():
    # нарушения, спрятанные в расшифровках звонков, добавляются к эталону
    try:
        import importlib.util
        _s = importlib.util.spec_from_file_location("calls", os.path.join(BASE, "calls.py"))
        _c = importlib.util.module_from_spec(_s); _s.loader.exec_module(_c)
        hidden = _c.hidden_violations()
        for d in D:
            for v in hidden.get(d["id"], []):
                if v not in d["verdict"]:
                    d["verdict"].append(v)
                    d.setdefault("hidden_in_call", []).append(v)
    except FileNotFoundError:
        pass
    for d in D:
        d["violations"] = [{"key": k, "clause": VIOLATIONS[k][0], "what": VIOLATIONS[k][1]}
                           for k in d["verdict"]]
    pack = {
        "_описание": "Сделки для проверки работы менеджеров по СТАНДАРТ.md. "
                     "verdict — эталонные нарушения (ключи), violations — с пунктами стандарта. "
                     "outcome: won (закрыта успешно) / lost (проиграна) / open (в работе).",
        "standard": "СТАНДАРТ.md",
        "violations_catalog": {k: {"clause": v[0], "what": v[1]} for k, v in VIOLATIONS.items()},
        "managers": MANAGERS,
        "deals": D,
    }
    json.dump(pack, open(os.path.join(BASE, "deals.json"), "w"), ensure_ascii=False, indent=1)

    # читаемый список сделок
    L = ["# Сделки для проверки — эталон", "",
         f"Всего {len(D)} сделок, менеджеров {len(MANAGERS)}. "
         "Нарушения привязаны к пунктам `СТАНДАРТ.md`.", "",
         "| Исход | Сколько |", "|---|---|"]
    oc = collections.Counter(d["outcome"] for d in D)
    for k, ru in [("won", "закрыты успешно"), ("lost", "проиграны"), ("open", "в работе")]:
        L.append(f"| {ru} | {oc[k]} |")
    L += ["", "## Каталог нарушений", "", "| Ключ | Пункт | Что нарушено |", "|---|---|---|"]
    for k, (c, w) in VIOLATIONS.items():
        L.append(f"| `{k}` | {c} | {w} |")
    L += ["", "## Сделки", ""]
    for d in D:
        L.append(f"### {d['id']} · {d['client']} · {d['amount']:,} ₽".replace(",", " "))
        L.append(f"Менеджер: **{d['manager']}** · стадия «{d['stage']}» · "
                 f"исход: **{ {'won':'закрыта','lost':'проиграна','open':'в работе'}[d['outcome']] }**"
                 + (f" ({d['loss_reason']})" if d.get("loss_reason") else ""))
        L.append(f"Создана {d['created']} · звонков {len(d['calls'])}")
        L.append("")
        for who, at, text in d["chat"]:
            L.append(f"- `{at}` **{'Клиент' if who == 'client' else 'Менеджер'}:** {text}")
        v = ", ".join(f"{x['clause']} ({x['key']})" for x in d["violations"]) or "нарушений нет"
        L.append("")
        L.append(f"**Эталон:** {v}")
        if d.get("note"):
            L.append(f"*Заметка: {d['note']}*")
        L.append("")
    open(os.path.join(BASE, "СДЕЛКИ.md"), "w").write("\n".join(L))

    # эталонная статистика — то, что должен получить ИИ
    M = ["# Эталонная статистика — что должен показать ИИ-контролёр", "",
         "Считается из `deals.json`. Если отчёт агента расходится с этим —",
         "он ошибся, а не «увидел иначе».", "", "## По менеджерам", "",
         "| Менеджер | Сделок | Закрыто | Проиграно | В работе | Нарушений | На сделку | Чаще всего нарушает |",
         "|---|---|---|---|---|---|---|---|"]
    for m in MANAGERS:
        ds = [d for d in D if d["manager"] == m]
        c = collections.Counter(k for d in ds for k in d["verdict"])
        top = ", ".join(f"{VIOLATIONS[k][0]}" for k, _ in c.most_common(2)) or "—"
        oc = collections.Counter(d["outcome"] for d in ds)
        nv = sum(len(d["verdict"]) for d in ds)
        M.append(f"| {m} | {len(ds)} | {oc['won']} | {oc['lost']} | {oc['open']} | {nv} "
                 f"| {nv/len(ds):.1f} | {top} |")
    M += ["", "## Закрытые против проигранных", "",
          "| | Закрыты успешно | Проиграны |", "|---|---|---|"]
    won = [d for d in D if d["outcome"] == "won"]
    lost = [d for d in D if d["outcome"] == "lost"]
    M.append(f"| Сделок | {len(won)} | {len(lost)} |")
    M.append(f"| Нарушений всего | {sum(len(d['verdict']) for d in won)} | {sum(len(d['verdict']) for d in lost)} |")
    M.append(f"| Нарушений на сделку | {sum(len(d['verdict']) for d in won)/len(won):.2f} "
             f"| {sum(len(d['verdict']) for d in lost)/len(lost):.2f} |")
    M.append(f"| Сделок без нарушений | {sum(1 for d in won if not d['verdict'])} "
             f"| {sum(1 for d in lost if not d['verdict'])} |")
    cw = collections.Counter(k for d in won for k in d["verdict"])
    cl = collections.Counter(k for d in lost for k in d["verdict"])
    M += ["", "### Какие нарушения встречаются в проигранных чаще", "",
          "| Пункт | Что нарушено | В проигранных | В закрытых |", "|---|---|---|---|"]
    for k, n in cl.most_common():
        M.append(f"| {VIOLATIONS[k][0]} | {VIOLATIONS[k][1]} | {n} | {cw.get(k, 0)} |")
    M += ["", "**Вывод, который обязан сделать ИИ:** сделки проигрываются не",
          "случайно — в проигранных систематически чаще нарушены пункты 3.2",
          "(согласился с возражением и пропал), 6.1 и 6.3 (молчание и брошенные",
          "сделки), 2.1–2.2 (цена без выяснения задачи). При этом есть честные",
          "проигрыши без нарушений (D-04, D-37) и выигрыши вопреки нарушениям",
          "(D-22, D-38) — значит связь есть, но она не абсолютная, и отчёт,",
          "утверждающий «все проигрыши по вине менеджеров», неверен."]
    open(os.path.join(BASE, "МЕНЕДЖЕРЫ.md"), "w").write("\n".join(M))

    total_oc = collections.Counter(d["outcome"] for d in D)
    print(f"Сделок: {len(D)} · менеджеров: {len(MANAGERS)} · "
          f"нарушений: {sum(len(d['verdict']) for d in D)}")
    print(f"Исходы: закрыто {total_oc['won']}, проиграно {total_oc['lost']}, "
          f"в работе {total_oc['open']}")
    print("Готово: deals.json · СДЕЛКИ.md · МЕНЕДЖЕРЫ.md")


if __name__ == "__main__":
    build()