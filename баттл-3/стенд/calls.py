def for_deal(deal_id, index=0):
    """Расшифровка звонка: deal_id и порядковый номер звонка в сделке."""
    calls = CALLS.get(deal_id)
    if not calls or index >= len(calls):
        return None
    return calls[index]


def as_text(call):
    head = "Расшифровка звонка (автоматическая):\n"
    return head + "\n".join(
        f"{'Менеджер' if who == 'М' else 'Клиент'}: {text}" for who, text in call["lines"])


def hidden_violations():
    """Нарушения, которые видны только в расшифровках."""
    out = {}
    for did, calls in CALLS.items():
        h = [v for c in calls for v in c["hidden"]]
        if h:
            out[did] = sorted(set(h))
    return out


if __name__ == "__main__":
    total = sum(len(v) for v in CALLS.values())
    hid = hidden_violations()
    print(f"Расшифровок: {total} по {len(CALLS)} сделкам")
    print(f"Сделок со скрытыми нарушениями (видны только в звонке): {len(hid)}")
    for k, v in hid.items():
        print(f"  {k}: {', '.join(v)}")
