#!/bin/bash
# Запуск ИИ-менеджера с автоперезапуском: если процесс упадёт, поднимется снова через 3 секунды.
# Состояние (заявки, сессии, очередь в Битрикс24) лежит в state.db и переживает перезапуск.
cd "$(dirname "$0")" || exit 1
while true; do
    echo "[$(date '+%F %T')] запуск app.py" >> app.log
    python3 app.py >> app.log 2>&1
    echo "[$(date '+%F %T')] app.py завершился с кодом $?, перезапуск через 3с" >> app.log
    sleep 3
done
